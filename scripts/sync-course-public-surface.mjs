#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export function projectPublicCourseSurface(contract) {
  if (!Array.isArray(contract?.courses)) {
    throw new Error("release registry courses are missing");
  }
  return {
    schemaVersion: 1,
    courses: contract.courses.map((course) => ({
      id: course.id,
      state: course.state,
      href: course.state === "published" ? course.href : null,
      titleKey: course.titleKey,
      primaryLocale: course.primaryLocale,
      contentLocales: course.contentLocales,
      progressEvent: course.state === "published"
        ? course.progress?.event ?? null
        : null,
    })),
  };
}

function generatedHeader() {
  return "// Generated by scripts/sync-course-public-surface.mjs. Do not edit.\n";
}

function publishedDashboardSource(courseId) {
  return `${generatedHeader()}import { courseLocaleParams } from "@/lib/release-surface";

export { default, generateMetadata } from "../_blocked/${courseId}/page";

export const dynamicParams = false;

export function generateStaticParams() {
  return courseLocaleParams("${courseId}");
}
`;
}

function publishedChildSource(courseId, parameter) {
  return `${generatedHeader()}import {
  courseChildParams,
  courseChildRouteValues,
} from "@/lib/release-surface";

export { default, generateMetadata } from "../../_blocked/${courseId}/[${parameter}]/page";

export const dynamicParams = false;

export function generateStaticParams() {
  return courseChildParams(
    "${courseId}",
    "${parameter}",
    courseChildRouteValues("${courseId}"),
  );
}
`;
}

/**
 * Project the stable public wrappers for authored courses whose implementation
 * is intentionally outside the public route graph while they are blocked.
 * A reviewed registry state flip regenerates these imports automatically.
 */
export function projectAuthoredCourseRouteWrappers(contract, projectRoot = process.cwd()) {
  if (!Array.isArray(contract?.courses)) {
    throw new Error("release registry courses are missing");
  }
  const blockedImplementationRoot = resolve(projectRoot, "app/[locale]/_blocked");
  if (!existsSync(blockedImplementationRoot)) return [];

  const wrappers = [];
  for (const entry of readdirSync(blockedImplementationRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const courseId = entry.name;
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(courseId)) {
      throw new Error(`unsafe authored course id: ${courseId}`);
    }
    const course = contract.courses.find((item) => item.id === courseId);
    if (!course) throw new Error(`authored course is missing from registry: ${courseId}`);
    if (course.state !== "blocked" && course.state !== "published") {
      throw new Error(`authored course ${courseId} must be blocked or published`);
    }
    const routeRoot = course.routes?.[0]?.replace(/\/$/, "");
    if (!routeRoot || routeRoot.includes("/")) {
      throw new Error(`authored course ${courseId} must have a one-segment dashboard route`);
    }

    wrappers.push({
      path: resolve(projectRoot, `app/[locale]/${routeRoot}/page.tsx`),
      source: course.state === "published"
        ? publishedDashboardSource(courseId)
        : null,
    });

    const implementationDirectory = join(blockedImplementationRoot, courseId);
    const dynamicEntries = readdirSync(implementationDirectory, { withFileTypes: true })
      .filter((child) => child.isDirectory() && /^\[[^\]]+\]$/.test(child.name));
    if (dynamicEntries.length !== 1) {
      throw new Error(`authored course ${courseId} must have exactly one dynamic child route`);
    }
    const parameter = dynamicEntries[0].name.slice(1, -1);
    wrappers.push({
      path: resolve(projectRoot, `app/[locale]/${routeRoot}/[${parameter}]/page.tsx`),
      source: course.state === "published"
        ? publishedChildSource(courseId, parameter)
        : null,
    });
  }
  return wrappers.sort((left, right) => left.path.localeCompare(right.path));
}

export function syncPublicCourseSurface(options = {}) {
  const projectRoot = resolve(options.projectRoot ?? process.cwd());
  const registryPath = resolve(projectRoot, "config/course-release-surface.json");
  const outputPath = resolve(projectRoot, "config/course-public-surface.json");
  if (!existsSync(registryPath)) throw new Error("course release registry is missing");
  const contract = JSON.parse(readFileSync(registryPath, "utf8"));
  const serialized = `${JSON.stringify(projectPublicCourseSurface(contract), null, 2)}\n`;
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  const wrapperOutputs = projectAuthoredCourseRouteWrappers(contract, projectRoot);
  const staleWrappers = wrapperOutputs.filter(({ path, source }) => (
    source === null
      ? existsSync(path)
      : !existsSync(path) || readFileSync(path, "utf8") !== source
  ));
  const changed = current !== serialized || staleWrappers.length > 0;
  if (options.check === true) {
    if (changed) throw new Error("client-safe course projection or public route wrappers are stale");
    return { changed: false, outputPath, wrapperPaths: wrapperOutputs.map(({ path }) => path) };
  }
  if (current !== serialized) writeFileSync(outputPath, serialized);
  for (const { path, source } of staleWrappers) {
    if (source === null) {
      const existing = readFileSync(path, "utf8");
      if (!existing.startsWith(generatedHeader())) {
        throw new Error(`refusing to remove non-generated public route wrapper: ${path}`);
      }
      rmSync(path);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, source);
  }
  return { changed, outputPath, wrapperPaths: wrapperOutputs.map(({ path }) => path) };
}

const invoked = process.argv[1]
  && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (invoked) {
  try {
    const result = syncPublicCourseSurface({ check: process.argv.includes("--check") });
    console.log(
      `release surface projection: ${result.changed ? "updated" : "current"} — ${result.outputPath}`,
    );
  } catch (error) {
    console.error(
      `release surface projection: FAIL — ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exitCode = 1;
  }
}
