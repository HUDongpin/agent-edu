import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const PROJECT = resolve(process.cwd());
const CONTRACT_PATH = join(PROJECT, "config", "course-release-surface.json");
const PACKAGE_PATH = join(PROJECT, "package.json");
const README_PATH = join(PROJECT, "README.md");

function fail(message) {
  throw new Error(message);
}

function assert(condition, message) {
  if (!condition) fail(message);
}

function assertUnique(values, label) {
  assert(new Set(values).size === values.length, `${label} must be unique`);
}

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function assertGateExists(command, packageJson) {
  const npmGate = /^npm run ([a-z0-9:-]+)$/.exec(command);
  if (npmGate) {
    assert(
      typeof packageJson.scripts?.[npmGate[1]] === "string",
      `release gate names missing package script ${npmGate[1]}`,
    );
    return;
  }

  const nodeGate = /^node (scripts\/[a-z0-9-]+\.mjs) --release$/.exec(command);
  assert(nodeGate, `unsupported release gate command: ${command}`);
  assert(existsSync(join(PROJECT, nodeGate[1])), `release gate file is missing: ${nodeGate[1]}`);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function assertReadmePublicationBoundary(contract, blocked) {
  const readme = readFileSync(README_PATH, "utf8");
  const englishMessages = readJson(join(PROJECT, "messages", "en.json"));
  for (const course of blocked) {
    const routeRoot = course.routes[0];
    assert(typeof routeRoot === "string", `${course.id} blocked route root is required`);
    const routePrefix = routeRoot.replace(/\/+$/, "");
    for (const locale of contract.siteLocales) {
      const publicPath = `/${locale}/${routePrefix}`;
      const publicPathPattern = new RegExp(
        `${escapeRegExp(publicPath)}(?:/|[?#]|$)`,
      );
      assert(
        !publicPathPattern.test(readme),
        `README.md must not promote blocked course route ${publicPath}`,
      );
    }

    const englishTitle = englishMessages[course.titleKey];
    assert(typeof englishTitle === "string", `${course.id} English title is required`);
    assert(
      !new RegExp(`^## Course: ${escapeRegExp(englishTitle)}\\s*$`, "m").test(readme),
      `README.md must not publish a detailed section for blocked course ${course.id}`,
    );
    assert(
      !readme.includes(course.releaseGate),
      `README.md must not describe blocked gate ${course.releaseGate} as a public release requirement`,
    );
  }
}

function assertRouteWiring(course) {
  // Blocked authored implementations must be unreachable from the public App
  // Router graph. Registry sync creates their wrappers only after publication.
  const routeRoot = "app/[locale]";
  const roots = [...new Set(course.routes.map((route) => route.split("/")[0]))];
  for (const root of roots) {
    const file = `${routeRoot}/${root}/page.tsx`;
    const authoredImplementation = join(PROJECT, routeRoot, "_blocked", course.id);
    const authored = existsSync(authoredImplementation);
    if (authored && course.state === "blocked") {
      assert(
        existsSync(join(authoredImplementation, "page.tsx")),
        `${course.id} must retain its internal dashboard implementation`,
      );
      assert(!existsSync(join(PROJECT, file)), `${file} must not exist while blocked`);
      for (const entry of readdirSync(authoredImplementation, { withFileTypes: true })) {
        if (!entry.isDirectory() || !/^\[[^\]]+\]$/.test(entry.name)) continue;
        assert(
          existsSync(join(authoredImplementation, entry.name, "page.tsx")),
          `${course.id} must retain its internal child implementation`,
        );
        assert(
          !existsSync(join(PROJECT, routeRoot, root, entry.name, "page.tsx")),
          `${routeRoot}/${root}/${entry.name}/page.tsx must not exist while blocked`,
        );
      }
      continue;
    }

    assert(existsSync(join(PROJECT, file)), `${file} must exist for registry route ${root}/`);
    const source = readFileSync(join(PROJECT, file), "utf8");
    assert(
      source.includes(`courseLocaleParams("${course.id}")`),
      `${file} must consume courseLocaleParams("${course.id}")`,
    );
    if (authored) {
      assert(
        source.startsWith("// Generated by scripts/sync-course-public-surface.mjs."),
        `${file} must be generated from registry state`,
      );
      assert(
        source.includes(`_blocked/${course.id}/page`),
        `${file} must activate the authored implementation after publication`,
      );
    }

    const rootDirectory = join(PROJECT, routeRoot, root);
    for (const entry of readdirSync(rootDirectory, { withFileTypes: true })) {
      if (!entry.isDirectory() || !/^\[[^\]]+\]$/.test(entry.name)) continue;
      const childFile = `${routeRoot}/${root}/${entry.name}/page.tsx`;
      assert(existsSync(join(PROJECT, childFile)), `${childFile} must exist for dynamic course routes`);
      const childSource = readFileSync(join(PROJECT, childFile), "utf8");
      assert(
        childSource.includes("courseChildParams("),
        `${childFile} must consume courseChildParams`,
      );
      assert(
        new RegExp(`courseChildParams\\(\\s*["']${course.id}["']`).test(childSource),
        `${childFile} must bind child params to ${course.id}`,
      );
      if (authored) {
        assert(
          childSource.includes(`_blocked/${course.id}/${entry.name}/page`),
          `${childFile} must activate the authored child implementation after publication`,
        );
      }
    }
  }
}

export function validateReleaseSurface(contract, packageJson) {
  assert(contract?.schemaVersion === 2, "release surface schemaVersion must be 2");
  assert(Array.isArray(contract.siteLocales), "siteLocales must be an array");
  assertUnique(contract.siteLocales, "siteLocales");
  assert(contract.siteLocales.includes("en"), "siteLocales must include English");
  assert(Array.isArray(contract.core?.contentLocales), "core.contentLocales must be an array");
  assert(Array.isArray(contract.core?.routes), "core.routes must be an array");
  assertUnique(contract.core.contentLocales, "core.contentLocales");
  assertUnique(contract.core.routes, "core.routes");
  assert(Array.isArray(contract.courses), "courses must be an array");

  const publicSurface = readJson(join(PROJECT, "config", "course-public-surface.json"));
  assert(publicSurface.schemaVersion === 1, "public course surface schemaVersion must be 1");
  assert(Array.isArray(publicSurface.courses), "public course surface courses must be an array");
  const expectedPublicProjection = contract.courses.map((course) => ({
    id: course.id,
    state: course.state,
    href: course.state === "published" ? course.href : null,
    titleKey: course.titleKey,
    primaryLocale: course.primaryLocale,
    contentLocales: course.contentLocales,
    progressEvent: course.state === "published" ? course.progress?.event ?? null : null,
  }));
  assert(
    JSON.stringify(publicSurface.courses) === JSON.stringify(expectedPublicProjection),
    "client-safe course surface must exactly match the public registry projection",
  );

  assertUnique(contract.courses.map((course) => course.id), "course ids");

  const published = contract.courses.filter((course) => course.state === "published");
  const blocked = contract.courses.filter((course) => course.state === "blocked");
  const roadmap = contract.courses.filter((course) => course.state === "roadmap");
  const allRoutes = [...contract.core.routes];
  for (const course of contract.courses) {
    assert(
      course.state === "published" || course.state === "blocked" || course.state === "roadmap",
      `${course.id} has invalid state`,
    );
    assert(typeof course.titleKey === "string" && course.titleKey.length > 0, `${course.id} titleKey is required`);
    assert(Array.isArray(course.contentLocales), `${course.id} contentLocales must be an array`);
    assert(Array.isArray(course.routes), `${course.id} routes must be an array`);
    assertUnique(course.contentLocales, `${course.id} contentLocales`);
    assertUnique(course.routes, `${course.id} routes`);
    assert(
      course.contentLocales.every((locale) => contract.siteLocales.includes(locale)),
      `${course.id} declares an unknown content locale`,
    );
    assert(
      course.routes.every((route) => route && !route.startsWith("/") && route.endsWith("/")),
      `${course.id} routes must be non-empty, relative, and slash-terminated`,
    );

    if (course.state === "roadmap") {
      assert(course.href === null, `${course.id} roadmap href must be null`);
      assert(course.primaryLocale === null, `${course.id} roadmap primaryLocale must be null`);
      assert(course.contentLocales.length === 0, `${course.id} roadmap contentLocales must be empty`);
      assert(course.routes.length === 0, `${course.id} roadmap routes must be empty`);
      assert(course.releaseGate === null, `${course.id} roadmap releaseGate must be null`);
      assert(course.progress === null, `${course.id} roadmap progress must be null`);
      continue;
    }

    assert(typeof course.href === "string", `${course.id} href is required`);
    assert(course.href === `/${course.routes[0]}`, `${course.id} href must target its first route`);
    assert(typeof course.primaryLocale === "string", `${course.id} primaryLocale is required`);
    assert(
      course.contentLocales.includes(course.primaryLocale),
      `${course.id} primaryLocale must be one of its contentLocales`,
    );
    assert(typeof course.releaseGate === "string", `${course.id} must declare exactly one releaseGate`);
    assertGateExists(course.releaseGate, packageJson);
    assert(course.progress && typeof course.progress === "object", `${course.id} progress is required`);
    assert(typeof course.progress.strategy === "string", `${course.id} progress.strategy is required`);
    assert(typeof course.progress.storageKey === "string", `${course.id} progress.storageKey is required`);
    assert(
      course.progress.event === null || typeof course.progress.event === "string",
      `${course.id} progress.event must be a string or null`,
    );
    if (course.state === "blocked") {
      assert(Array.isArray(course.blockers) && course.blockers.length > 0, `${course.id} blockers are required`);
    }
    allRoutes.push(...course.routes);
    assertRouteWiring(course);
  }

  assertUnique(allRoutes, "localized routes");
  const sitemapSource = readFileSync(join(PROJECT, "app", "sitemap.ts"), "utf8");
  assert(sitemapSource.includes("PAGES.flatMap"), "sitemap must iterate the published SEO projection");
  assert(sitemapSource.includes("contentLocalesForPage"), "sitemap must use registry contentLocales");
  const seoSource = readFileSync(join(PROJECT, "lib", "seo.ts"), "utf8");
  assert(
    seoSource.includes("export const PAGES = PUBLISHED_LOCALIZED_PAGES"),
    "SEO pages must be the registry-derived published route projection",
  );
  for (const clientPath of [
    "components/courses/Catalog.tsx",
    "components/CourseLocaleReturn.tsx",
    "components/progress-adapters.ts",
    "lib/public-courses.ts",
  ]) {
    const source = readFileSync(join(PROJECT, clientPath), "utf8");
    assert(
      !/from\s+["']@?\/?(?:\.\/)?lib\/release-surface["']/.test(source)
        && !/from\s+["']\.\/release-surface["']/.test(source),
      `${clientPath} must consume the client-safe public release projection`,
    );
  }
  const robotsSource = readFileSync(join(PROJECT, "app", "robots.ts"), "utf8");
  assert(
    !robotsSource.includes("blockedRobotsPaths") && !robotsSource.includes("disallow"),
    "robots must not disclose blocked or roadmap course prefixes",
  );
  const coursesPageSource = readFileSync(
    join(PROJECT, "app", "[locale]", "courses", "page.tsx"),
    "utf8",
  );
  assert(
    coursesPageSource.includes("PUBLISHED_CATALOG_COURSES.map"),
    "course collection JSON-LD must enumerate only published courses",
  );
  assert(
    coursesPageSource.includes("courseHrefFor(course.id, locale)"),
    "course collection JSON-LD must use registry-resolved hrefs",
  );
  assertReadmePublicationBoundary(contract, blocked);

  return { published, blocked, roadmap };
}

export function publishedGateLedger(contract) {
  const { published, blocked } = validateReleaseSurface(contract, readJson(PACKAGE_PATH));
  return {
    schemaVersion: 2,
    publishedCount: published.length,
    blockedCount: blocked.length,
    gates: published.map((course) => ({
      courseId: course.id,
      primaryLocale: course.primaryLocale,
      contentLocales: course.contentLocales,
      routeCount: course.routes.length,
      releaseGate: course.releaseGate,
    })),
  };
}

export function checkReleaseSurface() {
  const contract = readJson(CONTRACT_PATH);
  const packageJson = readJson(PACKAGE_PATH);
  const result = validateReleaseSurface(contract, packageJson);
  return {
    contract,
    published: result.published.length,
    blocked: result.blocked.length,
    roadmap: result.roadmap.length,
  };
}

const invoked = process.argv[1]
  && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (invoked) {
  try {
    const result = checkReleaseSurface();
    if (process.argv.includes("--ledger")) {
      console.log(JSON.stringify(publishedGateLedger(result.contract), null, 2));
    } else {
      console.log(
        `release surface: PASS — ${result.published} published, `
        + `${result.blocked} blocked, ${result.roadmap} roadmap`,
      );
    }
  } catch (error) {
    console.error(
      "release surface: FAIL — "
      + (error instanceof Error ? error.message : String(error)),
    );
    process.exitCode = 1;
  }
}
